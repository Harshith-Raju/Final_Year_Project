"""
Layer 6 - Subsystem A: Output Secret Scanner.
Scans the generated LLM response against all registered original vault secrets,
verifying that the model has not regurgitated or reconstructed protected data.
"""

from typing import List, Dict, Any, Set
from ..detection.pattern_matcher import SecretPatternMatcher


class OutputSecretScanner:
    """
    Guarantees Zero Egress Leakage on LLM output.
    """

    def __init__(self):
        self.pattern_matcher = SecretPatternMatcher()

    def check_for_leaks(self, response_text: str, registered_secrets: Set[str]) -> Dict[str, Any]:
        """
        Validates that no registered secrets, secret fragments, or new raw private keys appear in response_text.
        """
        leaks_detected: List[str] = []

        # 1. Exact & Substring match against all known secrets in this session's vault
        for secret in registered_secrets:
            if not secret or len(secret) < 4:
                continue
            # Direct match
            if secret in response_text:
                leaks_detected.append(secret)
                continue
            # Also catch high-significance fragments (first 80% or >=12 chars) to prevent partial leakage
            if len(secret) >= 12:
                sig_fragment = secret[:12]
                if sig_fragment in response_text:
                    leaks_detected.append(secret)

        # 2. Check for unexpected live private keys or tokens newly generated by the LLM
        # Placeholders (e.g. __SECRET_TOKEN_1__) are intended and allowed in the LLM response
        new_secrets = self.pattern_matcher.scan_text(response_text)
        high_risk_matches = []
        for m in new_secrets:
            val = m["value"]
            if val.startswith("__") and val.endswith("__"):
                continue  # Safe placeholder token
            if m["type"] == "regex_rule":
                high_risk_matches.append(m)

        is_safe = (len(leaks_detected) == 0 and len(high_risk_matches) == 0)

        return {
            "is_safe": is_safe,
            "leakage_count": len(leaks_detected),
            "leaked_secrets_preview": [f"{s[:3]}***{s[-2:]}" for s in leaks_detected],
            "unexpected_tokens_found": [m["rule"] for m in high_risk_matches],
        }
